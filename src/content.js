export function readsMarkup(className = "reads") {
  return Object.entries(reads)
    .map(
      ([cat, items]) =>
        `<div class="${className}__cat"><h3>${cat}</h3><p>${items.join(" · ")}</p></div>`
    )
    .join("");
}
